template <typename PubCloudT>
void publish_map(PubCloudT pubLaserCloudMap)
{
    PointCloudXYZI::Ptr laserCloudFullRes(dense_pub_en ? feats_undistort : feats_down_body);
    int size = laserCloudFullRes->points.size();
    PointCloudXYZI::Ptr laserCloudWorld( \
                    new PointCloudXYZI(size, 1));

    for (int i = 0; i < size; i++)
    {
        RGBpointBodyToWorld(&laserCloudFullRes->points[i], \
                            &laserCloudWorld->points[i]);
    }
    *pcl_wait_pub += *laserCloudWorld;

    // Bounded: this used to grow without limit. Downsampling converges it to the
    // space visited, the cap is a backstop. Also sets save_to_pcd()'s resolution.
    {
        pcl::VoxelGrid<PointType> vg;
        const float leaf = filter_size_map_min > 0 ? filter_size_map_min : 0.2f;
        vg.setLeafSize(leaf, leaf, leaf);
        vg.setInputCloud(pcl_wait_pub);
        PointCloudXYZI::Ptr reduced(new PointCloudXYZI());
        vg.filter(*reduced);
        pcl_wait_pub.swap(reduced);
        if (pcl_wait_pub->size() > MAP_PUB_MAX_POINTS) {
            RCLCPP_WARN_THROTTLE(lio_logger(), lio_clock(), 30000,
                "/Laser_map holds %zu points after downsampling (cap %d); "
                "clearing. Raise filter_size_map_min, or set publish.map_en false "
                "if you do not need this cloud.",
                pcl_wait_pub->size(), MAP_PUB_MAX_POINTS);
            pcl_wait_pub->clear();
        }
    }

    sensor_msgs::msg::PointCloud2 laserCloudmsg;
    pcl::toROSMsg(*pcl_wait_pub, laserCloudmsg);
    // laserCloudmsg.header.stamp = ros::Time().fromSec(lidar_end_time);
    laserCloudmsg.header.stamp = get_ros_time(lidar_end_time);
    laserCloudmsg.header.frame_id = map_frame;
    pubLaserCloudMap->publish(laserCloudmsg);
}

